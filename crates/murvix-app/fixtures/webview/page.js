const $ = id => document.getElementById(id);
const status = message => { $('status').textContent = message; };
const bind = (id, action) => { if ($(id)) $(id).onclick = () => Promise.resolve().then(action).catch(error => status(error.message)); };
const viewport = () => { $('viewport').textContent = `${innerWidth} × ${innerHeight}`; };
addEventListener('resize', viewport); viewport();
murvix.onFocus(focused => { if (focused) $('editor').focus(); });
murvix.onDataChange(data => status(JSON.stringify(data)));
murvix.onThemeChange(theme => status(`Theme: ${theme.colorScheme}`));
murvix.lifecycle.onBeforeClose(() => $('veto').checked);
status(JSON.stringify(murvix.data));
bind('modal', async () => status('Modal result: ' + JSON.stringify(await murvix.modal.openWebview({ entry:'modal.html', data:{message:'Hello from tab'} }))));
bind('fixed', async () => status('Modal result: ' + JSON.stringify(await murvix.modal.openWebview({entry:'modal.html', dismissOnOutsideClick:false}))));
bind('new', () => murvix.tabs.open({kind:'extensionWebView',extension:{id:murvix.extensionID,tabType:'demo',data:{message:'New instance'}}}));
bind('singleton', () => murvix.tabs.open({kind:'extensionWebView',extension:{id:murvix.extensionID,tabType:'demo',singleton:true,data:{updated:Date.now()}}}));
bind('rename', async () => { await murvix.tabs.setTitle('Retitled webview'); await murvix.tabs.setIcon('doc.text'); });
bind('submit', () => murvix.modal.submitWebview({text:$('editor').value}));
bind('self', () => murvix.lifecycle.close());

bind('right-panel', () => murvix.panels.open('right', {message:'Right panel'}));
bind('bottom-panel', () => murvix.panels.open('bottom', {message:'Bottom panel'}));
bind('close-panel', () => murvix.panels.close());
